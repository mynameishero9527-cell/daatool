def get_knowledge(keyword: str = "") -> list[dict]:
    kw = keyword.strip()
    if not kw:
        return [{"group": g["group"],
                 "items": [{"term": t, "desc": d} for t, d in g["items"]]} for g in KNOWLEDGE]
    out = []
    for g in KNOWLEDGE:
        items = [{"term": t, "desc": d} for t, d in g["items"] if kw in t or kw in d]
        if items:
            out.append({"group": g["group"], "items": items})
    return out
